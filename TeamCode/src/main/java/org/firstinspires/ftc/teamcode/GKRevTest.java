package org.firstinspires.ftc.teamcode;

// Εισαγωγή της κλάσης Disabled.
// Όταν χρησιμοποιείται το annotation @Disabled,
// το συγκεκριμένο OpMode δεν εμφανίζεται στη λίστα
// του Driver Station.
import com.qualcomm.robotcore.eventloop.opmode.Disabled;

// Η βασική κλάση OpMode.
// Όλα τα TeleOp και Autonomous που χρησιμοποιούν
// την iterative λογική κληρονομούν από αυτήν.
import com.qualcomm.robotcore.eventloop.opmode.OpMode;

// Annotation που δηλώνει ότι η κλάση αποτελεί
// ένα TeleOp πρόγραμμα και θα εμφανιστεί
// στην αντίστοιχη κατηγορία του Driver Station.
import com.qualcomm.robotcore.eventloop.opmode.TeleOp;

// ============================================================================
// Το annotation @TeleOp δηλώνει ότι η συγκεκριμένη κλάση
// αποτελεί πρόγραμμα χειροκίνητου ελέγχου (TeleOp).
// ============================================================================
@TeleOp

// ============================================================================
// Το annotation @Disabled απενεργοποιεί προσωρινά το OpMode.
//
// Το πρόγραμμα παραμένει στον κώδικα,
// αλλά δεν εμφανίζεται στη λίστα επιλογής
// του Driver Station.
//
// Είναι ιδιαίτερα χρήσιμο όταν θέλουμε
// να κρατήσουμε παλαιότερα παραδείγματα
// χωρίς να μπορούν να εκτελεστούν κατά λάθος.
// ============================================================================
@Disabled

// ============================================================================
// Η κλάση GKRevTest κληρονομεί από την OpMode.
//
// Αυτό σημαίνει ότι χρησιμοποιεί το Iterative OpMode,
// όπου:
//
// init()  -> εκτελείται μία φορά όταν πατηθεί INIT.
//
// loop()  -> εκτελείται συνεχώς (περίπου 50 φορές το δευτερόλεπτο)
//            όσο το OpMode βρίσκεται σε λειτουργία.
// ============================================================================
public class GKRevTest extends OpMode {

    // ========================================================================
    // Η init() εκτελείται μία μόνο φορά όταν ο οδηγός
    // πατήσει το κουμπί INIT στο Driver Station.
    //
    // Εδώ πραγματοποιείται συνήθως:
    // • η αρχικοποίηση των κινητήρων
    // • η αρχικοποίηση των αισθητήρων
    // • η φόρτωση παραμέτρων
    // • η εμφάνιση αρχικών πληροφοριών στο Telemetry
    // ========================================================================
    @Override
    public void init() {

        // Εμφάνιση μηνύματος στο Telemetry.
        //
        // Το πρώτο όρισμα αποτελεί τον τίτλο (Caption)
        // ενώ το δεύτερο αποτελεί την τιμή (Value).
        telemetry.addData("Hello", "World");

        // Δεύτερη γραμμή Telemetry.
        //
        // Οι πληροφορίες αυτές εμφανίζονται
        // στην οθόνη του Driver Station
        // όταν γίνει INIT του προγράμματος.
        telemetry.addData("Gavriil", "Karpathios");
    }

    // ========================================================================
    // Η loop() εκτελείται συνεχώς όσο το OpMode
    // βρίσκεται σε κατάσταση RUNNING.
    //
    // Συνήθως εδώ τοποθετούμε:
    //
    // • Ανάγνωση των joystick.
    // • Ανάγνωση κουμπιών.
    // • Έλεγχο κινητήρων.
    // • Έλεγχο servo.
    // • Ενημέρωση Telemetry.
    //
    // Στο συγκεκριμένο παράδειγμα η μέθοδος είναι κενή,
    // καθώς χρησιμοποιείται μόνο ως ένα απλό δοκιμαστικό OpMode.
    // ========================================================================
    @Override
    public void loop() {

    }
}